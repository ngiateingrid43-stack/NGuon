export function getWeaponDefinition(weaponId: WeaponId): WeaponDefinition {
  return WEAPONS_CONFIG[weaponId];
}

export function getScaledWeaponStats(weaponId: WeaponId, rarity: Rarity): WeaponStats {
  const base = WEAPONS_CONFIG[weaponId].stats;
  const mult = RARITY_DAMAGE_MULTIPLIER[rarity];
  return {
    ...base,
    damage: Math.round(base.damage * mult),
    reloadTime: Number((base.reloadTime / (1 + (mult - 1) * 0.5)).toFixed(2)),
  };
}

export function createInitialWeaponState(weaponId: WeaponId): WeaponRuntimeState {
  const def = getWeaponDefinition(weaponId);
  return {
    weaponId,
    ammoInMag: def.stats.magazineSize,
    reserveAmmo: def.stats.reserveAmmoMax,
    isReloading: false,
    reloadTimer: 0,
    fireCooldown: 0,
  };
}
